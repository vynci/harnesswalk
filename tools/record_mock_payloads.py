"""Record the payloads the web mock serves (web/src/mock/payloads.json).

The mock plays the recorded spec/examples streams; this runs the same three turns on the fake
provider against the starter pack and keeps each payload node's detail record, so the
inspector's Payload tab has real shapes and texts offline (tracer.md, "Payloads"). The stores
go to a scratch directory that is deleted afterwards.

    uv run python tools/record_mock_payloads.py
"""

from __future__ import annotations

import asyncio
import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from harnesswalk.ops.payloads import NODES  # noqa: E402
from tests.unit.support import harness, run_turn  # noqa: E402

# Recorded stream -> (message, the starter pack's fake fixture, approval decision).
TURNS = {
    "plain_answer": ("What are your support hours?", "plain_answer", None),
    "tool_call": ("Where is order A-1001?", "tool_call", None),
    "approval_pause": ("Please cancel order A-1002.", "cancel_order", "approve"),
}
OUT = ROOT / "web" / "src" / "mock" / "payloads.json"


async def record(fixture: str, message: str, approval: str | None, data: Path) -> list[dict]:
    h = harness(data, fixture, profile=None)
    try:
        events = await run_turn(h, message, approval=approval)
        out, seen = [], {}
        for e in events:
            if e.get("node_id") not in NODES or e["type"] not in ("node_enter", "node_exit"):
                continue
            key = (e["node_id"], e["type"])
            seen[key] = seen.get(key, -1) + 1
            detail = h.tracer.get_detail(e["tenant_id"], e.get("detail_ref") or "") or {}
            if "payload" in detail:
                out.append(
                    {
                        "node_id": e["node_id"],
                        "type": e["type"],
                        "occurrence": seen[key],
                        "payload": detail["payload"],
                    }
                )
        return out
    finally:
        await h.aclose()


async def main() -> None:
    doc: dict = {
        "_note": "Generated by tools/record_mock_payloads.py from fake-provider turns on the"
        " starter pack. The mock serves them for the matching recorded stream.",
        "messages": {name: message for name, (message, _, _) in TURNS.items()},
    }
    with tempfile.TemporaryDirectory() as tmp:
        for name, (message, fixture, approval) in TURNS.items():
            doc[name] = await record(fixture, message, approval, Path(tmp) / name)
    OUT.write_text(json.dumps(doc, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: " + ", ".join(f"{k} {len(doc[k])}" for k in TURNS))


if __name__ == "__main__":
    asyncio.run(main())
